/**
 * Full render shaders around an exported scene SDF: camera, march, normals,
 * shading and background, in WGSL (WebGPU) and GLSL ES 3.0 (WebGL2 /
 * Shadertoy). They reproduce the viewport's math (src/gpu/shader.ts) so an
 * embed looks like the editor without its grid, gizmo and highlights:
 *
 * - camera: orbit around `center`, uv from the top-left, world +Y down on
 *   screen; yaw rotates XZ, then pitch rotates YZ (same order as the editor)
 * - march: start at the scene bounding sphere, hit at HIT_EPS·max(t, 1),
 *   accept a REST_HIT_EPS leftover after the last step
 * - classic: one key light + iteration AO; chrome: reflection march + studio
 *   environment + SDF AO + ACES, tinted by the material; studio: GGX key
 *   light with soft shadow, sky ambient, reflections, AO, and a floor under
 *   the scene that catches the shadow (alpha-only on transparent pages)
 *
 * Export options are baked in as constants so the driver prunes what is off.
 */

export type EmbedStyle = "classic" | "chrome" | "studio";
export type EmbedBackground = "transparent" | "studio";

export interface RenderConstants {
  style: EmbedStyle;
  background: EmbedBackground;
  maxSteps: number;
  reflSteps: number;
  shadowSteps: number;
  /** Conservative origin-centered scene bounding radius (march bounds). */
  bounds: number;
  /** Studio floor: plane height (+Y is down, so the scene's lowest point) and reach. */
  floorY: number;
  floorCenter: readonly [number, number, number];
  floorReach: number;
}

/** The scene SDF and material functions the renderer calls. */
export interface SceneFns {
  sdf: string;
  sdfName: string;
  material: string;
  materialName: string;
}

const num = (n: number) => {
  const s = parseFloat(n.toFixed(6)).toString();
  return /[.e]/.test(s) ? s : `${s}.0`;
};

/** Must match shader.ts: HIT_EPS, REST_HIT_EPS. */
const HIT_EPS = 0.001;
const REST_HIT_EPS = 0.01;

const STYLE_ID: Record<EmbedStyle, number> = { classic: 0, chrome: 1, studio: 2 };

/** WGSL module with entry points vs / fs. */
export function renderWgsl(fns: SceneFns, c: RenderConstants): string {
  return `// ── Scene (generated by d-stance) ──────────────────────────────────────────

${fns.sdf}

${fns.material}

// ── Renderer ────────────────────────────────────────────────────────────────

struct View {
  res: vec2f,     // canvas size in pixels
  rot: vec2f,     // orbit yaw, pitch (radians)
  dist: f32,      // orbit distance
  time: f32,      // seconds
  center: vec3f,  // orbit center
}
@group(0) @binding(100) var<uniform> view: View;

const MAX_STEPS = ${c.maxSteps};
const REFL_STEPS = ${c.reflSteps};
const SHADOW_STEPS = ${c.shadowSteps};
const BOUNDS = ${num(c.bounds)};
const STYLE = ${STYLE_ID[c.style]}; // 0 classic, 1 chrome, 2 studio
const TRANSPARENT = ${c.background === "transparent"};
const FLOOR_Y = ${num(c.floorY)};
const FLOOR_CENTER = vec2f(${num(c.floorCenter[0])}, ${num(c.floorCenter[2])});
const FLOOR_REACH = ${num(c.floorReach)};
const KEY_LIGHT = vec3f(-0.33282, -0.83205, -0.44376); // normalize(-1.2, -3, -1.6)

fn map(p: vec3f) -> f32 {
  return ${fns.sdfName}(p);
}

fn rot2(v: vec2f, a: f32) -> vec2f {
  let c = cos(a);
  let s = sin(a);
  return vec2f(c * v.x + s * v.y, -s * v.x + c * v.y);
}

// Ray vs the scene's bounding sphere: (tEnter, tExit), tExit < 0 = miss.
fn bounds(ro: vec3f, rd: vec3f) -> vec2f {
  let b = dot(ro, rd);
  let h = b * b - (dot(ro, ro) - BOUNDS * BOUNDS);
  if (h < 0.0) { return vec2f(0.0, -1.0); }
  let sh = sqrt(h);
  return vec2f(max(-b - sh, 0.0), -b + sh);
}

// (t, iterations); t < 0 = miss.
fn march(ro: vec3f, rd: vec3f) -> vec2f {
  let span = bounds(ro, rd);
  if (span.y < 0.0) { return vec2f(-1.0, 0.0); }
  var t = span.x;
  var d = 0.0;
  var i = 0;
  for (; i < MAX_STEPS; i++) {
    d = map(ro + rd * t);
    t += d;
    if (d < ${num(HIT_EPS)} * max(t, 1.0)) { return vec2f(t, f32(i + 1)); }
    if (t > span.y) { return vec2f(-1.0, f32(i + 1)); }
  }
  if (d < ${num(REST_HIT_EPS)}) { return vec2f(t, f32(i)); }
  return vec2f(-1.0, f32(i));
}

fn normal(p: vec3f) -> vec3f {
  let e = 0.001;
  return normalize(
    vec3f(1.0, -1.0, -1.0) * map(p + vec3f(e, -e, -e)) +
    vec3f(-1.0, -1.0, 1.0) * map(p + vec3f(-e, -e, e)) +
    vec3f(-1.0, 1.0, -1.0) * map(p + vec3f(-e, e, -e)) +
    vec3f(1.0, 1.0, 1.0) * map(p + vec3f(e, e, e)));
}

fn ambientOcclusion(p: vec3f, n: vec3f) -> f32 {
  var occ = 0.0;
  var sca = 1.0;
  for (var i = 1.0; i <= 3.0; i += 1.0) {
    let hr = 0.01 + 0.12 * (i / 3.0);
    occ += (hr - map(p + n * hr)) * sca;
    sca *= 0.65;
  }
  return clamp(1.0 - 1.6 * occ, 0.0, 1.0);
}

// Soft shadow toward rd (IQ): 1 = lit, 0 = occluded.
fn softShadow(ro: vec3f, rd: vec3f) -> f32 {
  let span = bounds(ro, rd);
  if (span.y < 0.0) { return 1.0; }
  var res = 1.0;
  var t = max(span.x, 0.02);
  for (var i = 0; i < SHADOW_STEPS; i++) {
    let h = map(ro + rd * t);
    res = min(res, 8.0 * h / t);
    t += clamp(h, 0.01, 0.2);
    if (res < 0.002 || t > span.y) { break; }
  }
  let r = clamp(res, 0.0, 1.0);
  return r * r * (3.0 - 2.0 * r);
}

// Procedural studio: dark room + softbox strips ("up" is -Y).
fn env(rd: vec3f) -> vec3f {
  let dirUp = -rd.y;
  var v = mix(0.015, 0.06, dirUp * 0.5 + 0.5);
  let hl = max(length(rd.xz), 0.0001);
  let hx = rd.x / hl;
  let hz = rd.z / hl;
  let s1 = pow(max(hx * -0.7071 - hz * 0.7071, 0.0), 22.0) * (1.0 - smoothstep(0.55, 0.9, abs(rd.y)));
  let s2 = pow(max(hx * 0.866 - hz * 0.5, 0.0), 40.0) * (1.0 - smoothstep(0.5, 0.85, abs(rd.y)));
  let sTop = smoothstep(0.35, 0.85, dirUp);
  let sBot = smoothstep(0.3, 0.9, rd.y);
  v += s1 * 3.2 + s2 * 2.2 + sTop * 1.4 + sBot * 0.05;
  return vec3f(v);
}

fn aces(x: vec3f) -> vec3f {
  return clamp((x * (x * 2.51 + 0.03)) / (x * (x * 2.43 + 0.59) + 0.14), vec3f(0.0), vec3f(1.0));
}

// One bounce; like the editor, a march that runs out of steps still shades
// the point it reached. gain scales the bounced environment.
fn reflection(ro: vec3f, rd: vec3f, gain: f32) -> vec3f {
  let span = bounds(ro, rd);
  if (span.y < 0.0) { return env(rd); }
  var t = span.x;
  var d = 0.0;
  for (var i = 0; i < REFL_STEPS; i++) {
    d = map(ro + rd * t);
    if (d < 0.001 * max(t, 1.0)) { break; }
    t += d;
    if (t > span.y) { return env(rd); }
  }
  let p = ro + rd * t;
  let e = 0.001;
  let n = normalize(vec3f(map(p + vec3f(e, 0.0, 0.0)) - d, map(p + vec3f(0.0, e, 0.0)) - d, map(p + vec3f(0.0, 0.0, e)) - d));
  return env(reflect(rd, n)) * gain;
}

// Chrome reflections take the material's hue; gray stays neutral.
fn chromeTint(c: vec3f) -> vec3f {
  let hi = max(c.x, max(c.y, c.z));
  let lo = min(c.x, min(c.y, c.z));
  let sat = select(0.0, (hi - lo) / hi, hi > 0.001);
  return mix(vec3f(1.0), c / max(hi, 0.001), sat);
}

fn shadeClassic(n: vec3f, v: vec3f, iterations: f32, m: SdfMaterial) -> vec3f {
  let l = normalize(vec3f(2.0, -3.0, -1.0));
  let diff = max(dot(n, l), 0.0);
  let fresnel = pow(1.0 - abs(dot(n, v)), 3.0) * 0.5;
  let shininess = exp2(9.0 - 6.0 * m.roughness);
  let spec = pow(max(dot(n, normalize(l + v)), 0.0), shininess) * 3.0 * (1.0 - m.roughness);
  let ao = 1.0 - clamp(iterations / 64.0, 0.0, 1.0) * 0.4;
  let base = m.color * m.color / 0.72;
  let specCol = mix(vec3f(1.0), base, m.metalness);
  let diffCol = base * (1.0 - m.metalness * 0.85);
  return sqrt(max((diffCol * (diff * 0.8 + 0.2) + specCol * spec + base * fresnel) * ao + base * m.emission, vec3f(0.0)));
}

// Geometry-only work (marches) first, the material last: holding it across a
// loop that inlines the scene SDF costs registers.
fn shadeChrome(p: vec3f, n: vec3f, rd: vec3f) -> vec3f {
  let v = -rd;
  var refl = env(reflect(rd, n));
  if (REFL_STEPS > 0) { refl = reflection(p + n * 0.003, reflect(rd, n), 0.85); }
  let fresnel = 0.55 + 0.45 * pow(1.0 - max(dot(n, v), 0.0), 5.0);
  let h = normalize(normalize(vec3f(-1.5, -2.5, -2.0)) + v);
  let spec = pow(max(dot(n, h), 0.0), 220.0) * 2.5;
  let ao = ambientOcclusion(p, n);
  let m = ${fns.materialName}(p);
  let hdr = (refl * fresnel + vec3f(spec)) * mix(0.5, 1.0, ao) + m.color * m.emission;
  return pow(aces(hdr), vec3f(1.0 / 2.2)) * chromeTint(m.color);
}

fn shadeStudio(p: vec3f, n: vec3f, rd: vec3f) -> vec3f {
  let v = -rd;
  let ndl = max(dot(n, KEY_LIGHT), 0.0);
  var shadow = 0.0;
  if (ndl > 0.0) { shadow = softShadow(p + n * 0.003, KEY_LIGHT); }
  let ao = ambientOcclusion(p, n);
  let m = ${fns.materialName}(p);
  let albedo = pow(max(m.color, vec3f(0.0)), vec3f(2.2));
  let rough = clamp(m.roughness, 0.045, 1.0);
  let metal = clamp(m.metalness, 0.0, 1.0);
  let f0 = mix(vec3f(0.04), albedo, metal);
  let ndv = max(dot(n, v), 0.0001);
  var col = albedo * m.emission;
  if (ndl > 0.0) {
    let a2 = rough * rough * rough * rough;
    let h = normalize(KEY_LIGHT + v);
    let ndh = max(dot(n, h), 0.0);
    let vdh = max(dot(v, h), 0.0);
    let dd = ndh * ndh * (a2 - 1.0) + 1.0;
    let D = a2 / (3.14159265 * dd * dd);
    let k = (rough + 1.0) * (rough + 1.0) / 8.0;
    let G = (ndv / (ndv * (1.0 - k) + k)) * (ndl / (ndl * (1.0 - k) + k));
    let F = f0 + (vec3f(1.0) - f0) * pow(1.0 - vdh, 5.0);
    let spec = F * (D * G) / max(4.0 * ndv * ndl, 0.0001);
    let kd = (vec3f(1.0) - F) * (1.0 - metal);
    col += (kd * albedo / 3.14159265 + spec) * (2.6 * ndl * shadow);
  }
  let sky = mix(vec3f(0.035, 0.035, 0.04), vec3f(0.3, 0.31, 0.34), 0.5 - 0.5 * n.y);
  col += albedo * (1.0 - metal) * sky * ao;
  let fr = f0 + (max(vec3f(1.0 - rough), f0) - f0) * pow(1.0 - ndv, 5.0);
  let r = reflect(rd, n);
  var e = env(r);
  if (rough < 0.35 && REFL_STEPS > 0) { e = reflection(p + n * 0.003, r, 0.5); }
  e = mix(e, vec3f(0.1), clamp(rough * 1.3, 0.0, 1.0));
  col += e * fr * ao;
  return pow(aces(col), vec3f(1.0 / 2.2));
}

fn shade(ro: vec3f, rd: vec3f, t: f32, iterations: f32) -> vec3f {
  let p = ro + rd * t;
  let n = normal(p);
  if (STYLE == 1) { return shadeChrome(p, n, rd); }
  if (STYLE == 2) { return shadeStudio(p, n, rd); }
  return shadeClassic(n, -rd, iterations, ${fns.materialName}(p));
}

// Studio floor under the scene: (light, coverage). light 1 = lit, coverage 0 = off the floor.
fn floorLight(ro: vec3f, rd: vec3f) -> vec2f {
  if (STYLE != 2 || rd.y < 0.0001) { return vec2f(1.0, 0.0); }
  let tf = (FLOOR_Y - ro.y) / rd.y;
  if (tf <= 0.0) { return vec2f(1.0, 0.0); }
  let fp = ro + rd * tf;
  let near = 1.0 - smoothstep(FLOOR_REACH * 0.6, FLOOR_REACH * 2.2, length(fp.xz - FLOOR_CENTER));
  if (near < 0.001) { return vec2f(1.0, 0.0); }
  let lp = vec3f(fp.x, FLOOR_Y - 0.002, fp.z);
  let light = mix(0.35, 1.0, softShadow(lp, KEY_LIGHT)) * mix(0.45, 1.0, ambientOcclusion(lp, vec3f(0.0, -1.0, 0.0)));
  return vec2f(light, near);
}

@vertex
fn vs(@builtin(vertex_index) i: u32) -> @builtin(position) vec4f {
  let pos = array<vec2f, 3>(vec2f(-1.0, -1.0), vec2f(3.0, -1.0), vec2f(-1.0, 3.0));
  return vec4f(pos[i], 0.0, 1.0);
}

@fragment
fn fs(@builtin(position) frag: vec4f) -> @location(0) vec4f {
  let uvn = frag.xy / view.res * 2.0 - 1.0;
  let uv = vec2f(uvn.x * view.res.x / view.res.y, uvn.y);
  var ro = vec3f(0.0, 0.0, -view.dist);
  var rd = normalize(vec3f(uv, 1.0));
  let roXZ = rot2(ro.xz, view.rot.x);
  let rdXZ = rot2(rd.xz, view.rot.x);
  ro = vec3f(roXZ.x, ro.y, roXZ.y);
  rd = vec3f(rdXZ.x, rd.y, rdXZ.y);
  let roYZ = rot2(ro.yz, view.rot.y);
  let rdYZ = rot2(rd.yz, view.rot.y);
  ro = vec3f(ro.x, roYZ.x, roYZ.y) + view.center;
  rd = vec3f(rd.x, rdYZ.x, rdYZ.y);

  let hit = march(ro, rd);
  if (hit.x >= 0.0) { return vec4f(shade(ro, rd, hit.x, hit.y), 1.0); }
  let fl = floorLight(ro, rd);
  if (TRANSPARENT) { return vec4f(0.0, 0.0, 0.0, (1.0 - fl.x) * fl.y * 0.75); }
  let bg = mix(vec3f(0.055), vec3f(0.118), clamp(uvn.y * 0.5 + 0.5, 0.0, 1.0)) * clamp(1.0 - 0.175 * dot(uv, uv), 0.0, 1.0);
  return vec4f(bg * mix(1.0, fl.x, fl.y * 0.9) + vec3f(0.035) * (fl.y * fl.x), 1.0);
}
`;
}

/**
 * GLSL ES 3.0 body shared by WebGL2 and Shadertoy: expects `uRes`, `uRot`,
 * `uDist`, `uTarget` in scope and the scene functions. `render(frag)` takes
 * the pixel position from the top-left.
 */
function glslRenderer(fns: SceneFns, c: RenderConstants): string {
  return `#define MAX_STEPS ${c.maxSteps}
#define REFL_STEPS ${c.reflSteps}
#define SHADOW_STEPS ${c.shadowSteps}
#define STYLE ${STYLE_ID[c.style]}
#define TRANSPARENT ${c.background === "transparent" ? 1 : 0}
const float BOUNDS = ${num(c.bounds)};
const float FLOOR_Y = ${num(c.floorY)};
const vec2 FLOOR_CENTER = vec2(${num(c.floorCenter[0])}, ${num(c.floorCenter[2])});
const float FLOOR_REACH = ${num(c.floorReach)};
const vec3 KEY_LIGHT = vec3(-0.33282, -0.83205, -0.44376);

float map(vec3 p) {
  return ${fns.sdfName}(p);
}

vec2 rot2(vec2 v, float a) {
  float c = cos(a);
  float s = sin(a);
  return vec2(c * v.x + s * v.y, -s * v.x + c * v.y);
}

vec2 bounds(vec3 ro, vec3 rd) {
  float b = dot(ro, rd);
  float h = b * b - (dot(ro, ro) - BOUNDS * BOUNDS);
  if (h < 0.0) return vec2(0.0, -1.0);
  float sh = sqrt(h);
  return vec2(max(-b - sh, 0.0), -b + sh);
}

vec2 march(vec3 ro, vec3 rd) {
  vec2 span = bounds(ro, rd);
  if (span.y < 0.0) return vec2(-1.0, 0.0);
  float t = span.x;
  float d = 0.0;
  int i = 0;
  for (; i < MAX_STEPS; i++) {
    d = map(ro + rd * t);
    t += d;
    if (d < ${num(HIT_EPS)} * max(t, 1.0)) return vec2(t, float(i + 1));
    if (t > span.y) return vec2(-1.0, float(i + 1));
  }
  if (d < ${num(REST_HIT_EPS)}) return vec2(t, float(i));
  return vec2(-1.0, float(i));
}

vec3 calcNormal(vec3 p) {
  float e = 0.001;
  return normalize(
    vec3(1.0, -1.0, -1.0) * map(p + vec3(e, -e, -e)) +
    vec3(-1.0, -1.0, 1.0) * map(p + vec3(-e, -e, e)) +
    vec3(-1.0, 1.0, -1.0) * map(p + vec3(-e, e, -e)) +
    vec3(1.0, 1.0, 1.0) * map(p + vec3(e, e, e)));
}

float ambientOcclusion(vec3 p, vec3 n) {
  float occ = 0.0;
  float sca = 1.0;
  for (float i = 1.0; i <= 3.0; i += 1.0) {
    float hr = 0.01 + 0.12 * (i / 3.0);
    occ += (hr - map(p + n * hr)) * sca;
    sca *= 0.65;
  }
  return clamp(1.0 - 1.6 * occ, 0.0, 1.0);
}

float softShadow(vec3 ro, vec3 rd) {
  vec2 span = bounds(ro, rd);
  if (span.y < 0.0) return 1.0;
  float res = 1.0;
  float t = max(span.x, 0.02);
  for (int i = 0; i < SHADOW_STEPS; i++) {
    float h = map(ro + rd * t);
    res = min(res, 8.0 * h / t);
    t += clamp(h, 0.01, 0.2);
    if (res < 0.002 || t > span.y) break;
  }
  float r = clamp(res, 0.0, 1.0);
  return r * r * (3.0 - 2.0 * r);
}

vec3 env(vec3 rd) {
  float dirUp = -rd.y;
  float v = mix(0.015, 0.06, dirUp * 0.5 + 0.5);
  float hl = max(length(rd.xz), 0.0001);
  float hx = rd.x / hl;
  float hz = rd.z / hl;
  float s1 = pow(max(hx * -0.7071 - hz * 0.7071, 0.0), 22.0) * (1.0 - smoothstep(0.55, 0.9, abs(rd.y)));
  float s2 = pow(max(hx * 0.866 - hz * 0.5, 0.0), 40.0) * (1.0 - smoothstep(0.5, 0.85, abs(rd.y)));
  float sTop = smoothstep(0.35, 0.85, dirUp);
  float sBot = smoothstep(0.3, 0.9, rd.y);
  v += s1 * 3.2 + s2 * 2.2 + sTop * 1.4 + sBot * 0.05;
  return vec3(v);
}

vec3 aces(vec3 x) {
  return clamp((x * (x * 2.51 + 0.03)) / (x * (x * 2.43 + 0.59) + 0.14), 0.0, 1.0);
}

vec3 reflection(vec3 ro, vec3 rd, float gain) {
  vec2 span = bounds(ro, rd);
  if (span.y < 0.0) return env(rd);
  float t = span.x;
  float d = 0.0;
  for (int i = 0; i < REFL_STEPS; i++) {
    d = map(ro + rd * t);
    if (d < 0.001 * max(t, 1.0)) break;
    t += d;
    if (t > span.y) return env(rd);
  }
  vec3 p = ro + rd * t;
  float e = 0.001;
  vec3 n = normalize(vec3(map(p + vec3(e, 0.0, 0.0)) - d, map(p + vec3(0.0, e, 0.0)) - d, map(p + vec3(0.0, 0.0, e)) - d));
  return env(reflect(rd, n)) * gain;
}

vec3 chromeTint(vec3 c) {
  float hi = max(c.x, max(c.y, c.z));
  float lo = min(c.x, min(c.y, c.z));
  float sat = hi > 0.001 ? (hi - lo) / hi : 0.0;
  return mix(vec3(1.0), c / max(hi, 0.001), sat);
}

vec3 shadeClassic(vec3 n, vec3 v, float iterations, SdfMaterial m) {
  vec3 l = normalize(vec3(2.0, -3.0, -1.0));
  float diff = max(dot(n, l), 0.0);
  float fresnel = pow(1.0 - abs(dot(n, v)), 3.0) * 0.5;
  float shininess = exp2(9.0 - 6.0 * m.roughness);
  float spec = pow(max(dot(n, normalize(l + v)), 0.0), shininess) * 3.0 * (1.0 - m.roughness);
  float ao = 1.0 - clamp(iterations / 64.0, 0.0, 1.0) * 0.4;
  vec3 base = m.color * m.color / 0.72;
  vec3 specCol = mix(vec3(1.0), base, m.metalness);
  vec3 diffCol = base * (1.0 - m.metalness * 0.85);
  return sqrt(max((diffCol * (diff * 0.8 + 0.2) + specCol * spec + base * fresnel) * ao + base * m.emission, 0.0));
}

vec3 shadeChrome(vec3 p, vec3 n, vec3 rd) {
  vec3 v = -rd;
  vec3 refl = REFL_STEPS > 0 ? reflection(p + n * 0.003, reflect(rd, n), 0.85) : env(reflect(rd, n));
  float fresnel = 0.55 + 0.45 * pow(1.0 - max(dot(n, v), 0.0), 5.0);
  vec3 h = normalize(normalize(vec3(-1.5, -2.5, -2.0)) + v);
  float spec = pow(max(dot(n, h), 0.0), 220.0) * 2.5;
  float ao = ambientOcclusion(p, n);
  SdfMaterial m = ${fns.materialName}(p);
  vec3 hdr = (refl * fresnel + vec3(spec)) * mix(0.5, 1.0, ao) + m.color * m.emission;
  return pow(aces(hdr), vec3(1.0 / 2.2)) * chromeTint(m.color);
}

vec3 shadeStudio(vec3 p, vec3 n, vec3 rd) {
  vec3 v = -rd;
  float ndl = max(dot(n, KEY_LIGHT), 0.0);
  float shadow = ndl > 0.0 ? softShadow(p + n * 0.003, KEY_LIGHT) : 0.0;
  float ao = ambientOcclusion(p, n);
  SdfMaterial m = ${fns.materialName}(p);
  vec3 albedo = pow(max(m.color, 0.0), vec3(2.2));
  float rough = clamp(m.roughness, 0.045, 1.0);
  float metal = clamp(m.metalness, 0.0, 1.0);
  vec3 f0 = mix(vec3(0.04), albedo, metal);
  float ndv = max(dot(n, v), 0.0001);
  vec3 col = albedo * m.emission;
  if (ndl > 0.0) {
    float a2 = rough * rough * rough * rough;
    vec3 h = normalize(KEY_LIGHT + v);
    float ndh = max(dot(n, h), 0.0);
    float vdh = max(dot(v, h), 0.0);
    float dd = ndh * ndh * (a2 - 1.0) + 1.0;
    float D = a2 / (3.14159265 * dd * dd);
    float k = (rough + 1.0) * (rough + 1.0) / 8.0;
    float G = (ndv / (ndv * (1.0 - k) + k)) * (ndl / (ndl * (1.0 - k) + k));
    vec3 F = f0 + (vec3(1.0) - f0) * pow(1.0 - vdh, 5.0);
    vec3 spec = F * (D * G) / max(4.0 * ndv * ndl, 0.0001);
    vec3 kd = (vec3(1.0) - F) * (1.0 - metal);
    col += (kd * albedo / 3.14159265 + spec) * (2.6 * ndl * shadow);
  }
  vec3 sky = mix(vec3(0.035, 0.035, 0.04), vec3(0.3, 0.31, 0.34), 0.5 - 0.5 * n.y);
  col += albedo * (1.0 - metal) * sky * ao;
  vec3 fr = f0 + (max(vec3(1.0 - rough), f0) - f0) * pow(1.0 - ndv, 5.0);
  vec3 r = reflect(rd, n);
  vec3 e = (rough < 0.35 && REFL_STEPS > 0) ? reflection(p + n * 0.003, r, 0.5) : env(r);
  e = mix(e, vec3(0.1), clamp(rough * 1.3, 0.0, 1.0));
  col += e * fr * ao;
  return pow(aces(col), vec3(1.0 / 2.2));
}

vec3 shade(vec3 ro, vec3 rd, float t, float iterations) {
  vec3 p = ro + rd * t;
  vec3 n = calcNormal(p);
#if STYLE == 1
  return shadeChrome(p, n, rd);
#elif STYLE == 2
  return shadeStudio(p, n, rd);
#else
  return shadeClassic(n, -rd, iterations, ${fns.materialName}(p));
#endif
}

vec2 floorLight(vec3 ro, vec3 rd) {
#if STYLE == 2
  if (rd.y < 0.0001) return vec2(1.0, 0.0);
  float tf = (FLOOR_Y - ro.y) / rd.y;
  if (tf <= 0.0) return vec2(1.0, 0.0);
  vec3 fp = ro + rd * tf;
  float near = 1.0 - smoothstep(FLOOR_REACH * 0.6, FLOOR_REACH * 2.2, length(fp.xz - FLOOR_CENTER));
  if (near < 0.001) return vec2(1.0, 0.0);
  vec3 lp = vec3(fp.x, FLOOR_Y - 0.002, fp.z);
  float light = mix(0.35, 1.0, softShadow(lp, KEY_LIGHT)) * mix(0.45, 1.0, ambientOcclusion(lp, vec3(0.0, -1.0, 0.0)));
  return vec2(light, near);
#else
  return vec2(1.0, 0.0);
#endif
}

// frag: pixel position from the top-left corner.
vec4 render(vec2 frag) {
  vec2 uvn = frag / uRes * 2.0 - 1.0;
  vec2 uv = vec2(uvn.x * uRes.x / uRes.y, uvn.y);
  vec3 ro = vec3(0.0, 0.0, -uDist);
  vec3 rd = normalize(vec3(uv, 1.0));
  vec2 roXZ = rot2(ro.xz, uRot.x);
  vec2 rdXZ = rot2(rd.xz, uRot.x);
  ro = vec3(roXZ.x, ro.y, roXZ.y);
  rd = vec3(rdXZ.x, rd.y, rdXZ.y);
  vec2 roYZ = rot2(ro.yz, uRot.y);
  vec2 rdYZ = rot2(rd.yz, uRot.y);
  ro = vec3(ro.x, roYZ.x, roYZ.y) + uTarget;
  rd = vec3(rd.x, rdYZ.x, rdYZ.y);

  vec2 hit = march(ro, rd);
  if (hit.x >= 0.0) return vec4(shade(ro, rd, hit.x, hit.y), 1.0);
  vec2 fl = floorLight(ro, rd);
#if TRANSPARENT
  return vec4(0.0, 0.0, 0.0, (1.0 - fl.x) * fl.y * 0.75);
#else
  vec3 bg = mix(vec3(0.055), vec3(0.118), clamp(uvn.y * 0.5 + 0.5, 0.0, 1.0)) * clamp(1.0 - 0.175 * dot(uv, uv), 0.0, 1.0);
  return vec4(bg * mix(1.0, fl.x, fl.y * 0.9) + vec3(0.035) * (fl.y * fl.x), 1.0);
#endif
}`;
}

function glslScene(fns: SceneFns): string {
  return `// ── Scene (generated by d-stance) ──────────────────────────────────────────

${fns.sdf}

${fns.material}`;
}

/** WebGL2 fragment shader (pair with GL_VERTEX in the runtime). */
export function renderGlsl(fns: SceneFns, c: RenderConstants): string {
  return `#version 300 es
precision highp float;
precision highp int;

uniform vec2 uRes;    // canvas size in pixels
uniform vec2 uRot;    // orbit yaw, pitch (radians)
uniform float uDist;  // orbit distance
uniform float uTime;  // seconds
uniform vec3 uTarget; // orbit center
out vec4 outColor;

${glslScene(fns)}

// ── Renderer ────────────────────────────────────────────────────────────────

${glslRenderer(fns, c)}

void main() {
  outColor = render(vec2(gl_FragCoord.x, uRes.y - gl_FragCoord.y));
}
`;
}

/**
 * Shadertoy "Image" tab: paste as-is. Drag to orbit (iMouse); the view
 * starts where the editor camera was.
 */
export function renderShadertoy(
  fns: SceneFns,
  c: RenderConstants,
  view: { rotX: number; rotY: number; distance: number; target: readonly [number, number, number] },
): string {
  return `// Made with d-stance — drag to orbit.

${glslScene(fns)}

// ── Renderer ────────────────────────────────────────────────────────────────

vec2 uRes;
vec2 uRot;
float uDist;
vec3 uTarget;

${glslRenderer(fns, c)}

void mainImage(out vec4 fragColor, in vec2 fragCoord) {
  uRes = iResolution.xy;
  uRot = vec2(${num(view.rotX)}, ${num(view.rotY)});
  if (iMouse.x > 0.0) uRot += (iMouse.xy / iResolution.xy - 0.5) * vec2(6.2831853, -3.1415926);
  uDist = ${num(view.distance)};
  uTarget = vec3(${view.target.map(num).join(", ")});
  vec4 c = render(vec2(fragCoord.x, iResolution.y - fragCoord.y));
  fragColor = vec4(c.rgb + vec3(0.07) * (1.0 - c.a), 1.0);
}
`;
}
