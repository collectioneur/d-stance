/**
 * Full render shaders around an exported scene SDF: camera, march, normals,
 * shading and background, in WGSL (WebGPU) and GLSL ES 3.0 (WebGL2 /
 * Shadertoy). They reproduce the viewport's math (src/gpu/shader.ts) so an
 * embed looks like the editor without its grid, gizmo and highlights:
 *
 * - camera: orbit around the origin, uv from the top-left, world +Y down on
 *   screen; yaw rotates XZ, then pitch rotates YZ (same order as the editor)
 * - march: start at the scene bounding sphere, hit at HIT_EPS·max(t, 1),
 *   accept a REST_HIT_EPS leftover after the last step
 * - classic: one key light + iteration AO; chrome: reflection march + studio
 *   environment + SDF AO + ACES
 *
 * Export options are baked in as constants so the driver prunes what is off.
 */

export type EmbedStyle = "classic" | "chrome";
export type EmbedBackground = "transparent" | "studio";

export interface RenderConstants {
  style: EmbedStyle;
  background: EmbedBackground;
  maxSteps: number;
  reflSteps: number;
  /** Conservative origin-centered scene bounding radius. */
  bounds: number;
}

const num = (n: number) => {
  const s = parseFloat(n.toFixed(6)).toString();
  return /[.e]/.test(s) ? s : `${s}.0`;
};

/** Must match shader.ts: RAY_MISS_T, HIT_EPS, REST_HIT_EPS. */
const HIT_EPS = 0.001;
const REST_HIT_EPS = 0.01;

/** WGSL module: `sceneWgsl` defines `fnName(p: vec3f) -> f32`. Entry points vs / fs. */
export function renderWgsl(sceneWgsl: string, fnName: string, c: RenderConstants): string {
  return `// ── Scene SDF (generated by d-stance) ──────────────────────────────────────

${sceneWgsl}

// ── Renderer ────────────────────────────────────────────────────────────────

struct View {
  res: vec2f,     // canvas size in pixels
  rot: vec2f,     // orbit yaw, pitch (radians)
  dist: f32,      // orbit distance
  time: f32,      // seconds
  center: vec3f,  // orbit center
}
@group(0) @binding(100) var<uniform> view: View;

const MAX_STEPS = ${c.maxSteps};
const REFL_STEPS = ${c.reflSteps};
const BOUNDS = ${num(c.bounds)};
const CHROME = ${c.style === "chrome"};
const TRANSPARENT = ${c.background === "transparent"};

fn map(p: vec3f) -> f32 {
  return ${fnName}(p);
}

fn rot2(v: vec2f, a: f32) -> vec2f {
  let c = cos(a);
  let s = sin(a);
  return vec2f(c * v.x + s * v.y, -s * v.x + c * v.y);
}

// Ray vs the scene's bounding sphere: (tEnter, tExit), tExit < 0 = miss.
fn bounds(ro: vec3f, rd: vec3f) -> vec2f {
  let b = dot(ro, rd);
  let h = b * b - (dot(ro, ro) - BOUNDS * BOUNDS);
  if (h < 0.0) { return vec2f(0.0, -1.0); }
  let sh = sqrt(h);
  return vec2f(max(-b - sh, 0.0), -b + sh);
}

// (t, iterations); t < 0 = miss.
fn march(ro: vec3f, rd: vec3f) -> vec2f {
  let span = bounds(ro, rd);
  if (span.y < 0.0) { return vec2f(-1.0, 0.0); }
  var t = span.x;
  var d = 0.0;
  var i = 0;
  for (; i < MAX_STEPS; i++) {
    d = map(ro + rd * t);
    t += d;
    if (d < ${num(HIT_EPS)} * max(t, 1.0)) { return vec2f(t, f32(i + 1)); }
    if (t > span.y) { return vec2f(-1.0, f32(i + 1)); }
  }
  if (d < ${num(REST_HIT_EPS)}) { return vec2f(t, f32(i)); }
  return vec2f(-1.0, f32(i));
}

fn normal(p: vec3f) -> vec3f {
  let e = 0.001;
  return normalize(
    vec3f(1.0, -1.0, -1.0) * map(p + vec3f(e, -e, -e)) +
    vec3f(-1.0, -1.0, 1.0) * map(p + vec3f(-e, -e, e)) +
    vec3f(-1.0, 1.0, -1.0) * map(p + vec3f(-e, e, -e)) +
    vec3f(1.0, 1.0, 1.0) * map(p + vec3f(e, e, e)));
}

fn ambientOcclusion(p: vec3f, n: vec3f) -> f32 {
  var occ = 0.0;
  var sca = 1.0;
  for (var i = 1.0; i <= 3.0; i += 1.0) {
    let hr = 0.01 + 0.12 * (i / 3.0);
    occ += (hr - map(p + n * hr)) * sca;
    sca *= 0.65;
  }
  return clamp(1.0 - 1.6 * occ, 0.0, 1.0);
}

// Procedural studio: dark room + softbox strips ("up" is -Y).
fn env(rd: vec3f) -> vec3f {
  let dirUp = -rd.y;
  var v = mix(0.015, 0.06, dirUp * 0.5 + 0.5);
  let hl = max(length(rd.xz), 0.0001);
  let hx = rd.x / hl;
  let hz = rd.z / hl;
  let s1 = pow(max(hx * -0.7071 - hz * 0.7071, 0.0), 22.0) * (1.0 - smoothstep(0.55, 0.9, abs(rd.y)));
  let s2 = pow(max(hx * 0.866 - hz * 0.5, 0.0), 40.0) * (1.0 - smoothstep(0.5, 0.85, abs(rd.y)));
  let sTop = smoothstep(0.35, 0.85, dirUp);
  let sBot = smoothstep(0.3, 0.9, rd.y);
  v += s1 * 3.2 + s2 * 2.2 + sTop * 1.4 + sBot * 0.05;
  return vec3f(v);
}

fn aces(x: vec3f) -> vec3f {
  return clamp((x * (x * 2.51 + 0.03)) / (x * (x * 2.43 + 0.59) + 0.14), vec3f(0.0), vec3f(1.0));
}

// One bounce; like the editor, a march that runs out of steps still shades
// the point it reached.
fn reflection(ro: vec3f, rd: vec3f) -> vec3f {
  let span = bounds(ro, rd);
  if (span.y < 0.0) { return env(rd); }
  var t = span.x;
  var d = 0.0;
  for (var i = 0; i < REFL_STEPS; i++) {
    d = map(ro + rd * t);
    if (d < 0.001 * max(t, 1.0)) { break; }
    t += d;
    if (t > span.y) { return env(rd); }
  }
  let p = ro + rd * t;
  let e = 0.001;
  let n = normalize(vec3f(map(p + vec3f(e, 0.0, 0.0)) - d, map(p + vec3f(0.0, e, 0.0)) - d, map(p + vec3f(0.0, 0.0, e)) - d));
  return env(reflect(rd, n)) * 0.85;
}

fn shade(ro: vec3f, rd: vec3f, t: f32, iterations: f32) -> vec3f {
  let p = ro + rd * t;
  let n = normal(p);
  let v = -rd;
  if (CHROME) {
    var refl = env(reflect(rd, n));
    if (REFL_STEPS > 0) { refl = reflection(p + n * 0.003, reflect(rd, n)); }
    let fresnel = 0.55 + 0.45 * pow(1.0 - max(dot(n, v), 0.0), 5.0);
    let h = normalize(normalize(vec3f(-1.5, -2.5, -2.0)) + v);
    let spec = pow(max(dot(n, h), 0.0), 220.0) * 2.5;
    let hdr = (refl * fresnel + vec3f(spec)) * mix(0.5, 1.0, ambientOcclusion(p, n));
    return pow(aces(hdr), vec3f(1.0 / 2.2));
  }
  let l = normalize(vec3f(2.0, -3.0, -1.0));
  let diff = max(dot(n, l), 0.0);
  let fresnel = pow(1.0 - abs(dot(n, v)), 3.0) * 0.5;
  let spec = pow(max(dot(n, normalize(l + v)), 0.0), 64.0) * 1.5;
  let ao = 1.0 - clamp(iterations / 64.0, 0.0, 1.0) * 0.4;
  let base = vec3f(0.72);
  return sqrt(max((base * (diff * 0.8 + 0.2) + vec3f(spec) + base * fresnel) * ao, vec3f(0.0)));
}

@vertex
fn vs(@builtin(vertex_index) i: u32) -> @builtin(position) vec4f {
  let pos = array<vec2f, 3>(vec2f(-1.0, -1.0), vec2f(3.0, -1.0), vec2f(-1.0, 3.0));
  return vec4f(pos[i], 0.0, 1.0);
}

@fragment
fn fs(@builtin(position) frag: vec4f) -> @location(0) vec4f {
  let uvn = frag.xy / view.res * 2.0 - 1.0;
  let uv = vec2f(uvn.x * view.res.x / view.res.y, uvn.y);
  var ro = vec3f(0.0, 0.0, -view.dist);
  var rd = normalize(vec3f(uv, 1.0));
  let roXZ = rot2(ro.xz, view.rot.x);
  let rdXZ = rot2(rd.xz, view.rot.x);
  ro = vec3f(roXZ.x, ro.y, roXZ.y);
  rd = vec3f(rdXZ.x, rd.y, rdXZ.y);
  let roYZ = rot2(ro.yz, view.rot.y);
  let rdYZ = rot2(rd.yz, view.rot.y);
  ro = vec3f(ro.x, roYZ.x, roYZ.y) + view.center;
  rd = vec3f(rd.x, rdYZ.x, rdYZ.y);

  let hit = march(ro, rd);
  if (hit.x >= 0.0) { return vec4f(shade(ro, rd, hit.x, hit.y), 1.0); }
  if (TRANSPARENT) { return vec4f(0.0); }
  let bg = mix(vec3f(0.055), vec3f(0.118), clamp(uvn.y * 0.5 + 0.5, 0.0, 1.0));
  return vec4f(bg * clamp(1.0 - 0.175 * dot(uv, uv), 0.0, 1.0), 1.0);
}
`;
}

/**
 * GLSL ES 3.0 body shared by WebGL2 and Shadertoy: expects `uRes`, `uRot`,
 * `uDist` in scope and the scene SDF `fnName(vec3)`. Returns `render(frag)`
 * where frag is in pixels from the top-left.
 */
function glslRenderer(fnName: string, c: RenderConstants): string {
  return `#define MAX_STEPS ${c.maxSteps}
#define REFL_STEPS ${c.reflSteps}
#define CHROME ${c.style === "chrome" ? 1 : 0}
#define TRANSPARENT ${c.background === "transparent" ? 1 : 0}
const float BOUNDS = ${num(c.bounds)};

float map(vec3 p) {
  return ${fnName}(p);
}

vec2 rot2(vec2 v, float a) {
  float c = cos(a);
  float s = sin(a);
  return vec2(c * v.x + s * v.y, -s * v.x + c * v.y);
}

vec2 bounds(vec3 ro, vec3 rd) {
  float b = dot(ro, rd);
  float h = b * b - (dot(ro, ro) - BOUNDS * BOUNDS);
  if (h < 0.0) return vec2(0.0, -1.0);
  float sh = sqrt(h);
  return vec2(max(-b - sh, 0.0), -b + sh);
}

vec2 march(vec3 ro, vec3 rd) {
  vec2 span = bounds(ro, rd);
  if (span.y < 0.0) return vec2(-1.0, 0.0);
  float t = span.x;
  float d = 0.0;
  int i = 0;
  for (; i < MAX_STEPS; i++) {
    d = map(ro + rd * t);
    t += d;
    if (d < ${num(HIT_EPS)} * max(t, 1.0)) return vec2(t, float(i + 1));
    if (t > span.y) return vec2(-1.0, float(i + 1));
  }
  if (d < ${num(REST_HIT_EPS)}) return vec2(t, float(i));
  return vec2(-1.0, float(i));
}

vec3 calcNormal(vec3 p) {
  float e = 0.001;
  return normalize(
    vec3(1.0, -1.0, -1.0) * map(p + vec3(e, -e, -e)) +
    vec3(-1.0, -1.0, 1.0) * map(p + vec3(-e, -e, e)) +
    vec3(-1.0, 1.0, -1.0) * map(p + vec3(-e, e, -e)) +
    vec3(1.0, 1.0, 1.0) * map(p + vec3(e, e, e)));
}

float ambientOcclusion(vec3 p, vec3 n) {
  float occ = 0.0;
  float sca = 1.0;
  for (float i = 1.0; i <= 3.0; i += 1.0) {
    float hr = 0.01 + 0.12 * (i / 3.0);
    occ += (hr - map(p + n * hr)) * sca;
    sca *= 0.65;
  }
  return clamp(1.0 - 1.6 * occ, 0.0, 1.0);
}

vec3 env(vec3 rd) {
  float dirUp = -rd.y;
  float v = mix(0.015, 0.06, dirUp * 0.5 + 0.5);
  float hl = max(length(rd.xz), 0.0001);
  float hx = rd.x / hl;
  float hz = rd.z / hl;
  float s1 = pow(max(hx * -0.7071 - hz * 0.7071, 0.0), 22.0) * (1.0 - smoothstep(0.55, 0.9, abs(rd.y)));
  float s2 = pow(max(hx * 0.866 - hz * 0.5, 0.0), 40.0) * (1.0 - smoothstep(0.5, 0.85, abs(rd.y)));
  float sTop = smoothstep(0.35, 0.85, dirUp);
  float sBot = smoothstep(0.3, 0.9, rd.y);
  v += s1 * 3.2 + s2 * 2.2 + sTop * 1.4 + sBot * 0.05;
  return vec3(v);
}

vec3 aces(vec3 x) {
  return clamp((x * (x * 2.51 + 0.03)) / (x * (x * 2.43 + 0.59) + 0.14), 0.0, 1.0);
}

vec3 reflection(vec3 ro, vec3 rd) {
  vec2 span = bounds(ro, rd);
  if (span.y < 0.0) return env(rd);
  float t = span.x;
  float d = 0.0;
  for (int i = 0; i < REFL_STEPS; i++) {
    d = map(ro + rd * t);
    if (d < 0.001 * max(t, 1.0)) break;
    t += d;
    if (t > span.y) return env(rd);
  }
  vec3 p = ro + rd * t;
  float e = 0.001;
  vec3 n = normalize(vec3(map(p + vec3(e, 0.0, 0.0)) - d, map(p + vec3(0.0, e, 0.0)) - d, map(p + vec3(0.0, 0.0, e)) - d));
  return env(reflect(rd, n)) * 0.85;
}

vec3 shade(vec3 ro, vec3 rd, float t, float iterations) {
  vec3 p = ro + rd * t;
  vec3 n = calcNormal(p);
  vec3 v = -rd;
#if CHROME
  vec3 refl = REFL_STEPS > 0 ? reflection(p + n * 0.003, reflect(rd, n)) : env(reflect(rd, n));
  float fresnel = 0.55 + 0.45 * pow(1.0 - max(dot(n, v), 0.0), 5.0);
  vec3 h = normalize(normalize(vec3(-1.5, -2.5, -2.0)) + v);
  float spec = pow(max(dot(n, h), 0.0), 220.0) * 2.5;
  vec3 hdr = (refl * fresnel + vec3(spec)) * mix(0.5, 1.0, ambientOcclusion(p, n));
  return pow(aces(hdr), vec3(1.0 / 2.2));
#else
  vec3 l = normalize(vec3(2.0, -3.0, -1.0));
  float diff = max(dot(n, l), 0.0);
  float fresnel = pow(1.0 - abs(dot(n, v)), 3.0) * 0.5;
  float spec = pow(max(dot(n, normalize(l + v)), 0.0), 64.0) * 1.5;
  float ao = 1.0 - clamp(iterations / 64.0, 0.0, 1.0) * 0.4;
  vec3 base = vec3(0.72);
  return sqrt(max((base * (diff * 0.8 + 0.2) + vec3(spec) + base * fresnel) * ao, 0.0));
#endif
}

// frag: pixel position from the top-left corner.
vec4 render(vec2 frag) {
  vec2 uvn = frag / uRes * 2.0 - 1.0;
  vec2 uv = vec2(uvn.x * uRes.x / uRes.y, uvn.y);
  vec3 ro = vec3(0.0, 0.0, -uDist);
  vec3 rd = normalize(vec3(uv, 1.0));
  vec2 roXZ = rot2(ro.xz, uRot.x);
  vec2 rdXZ = rot2(rd.xz, uRot.x);
  ro = vec3(roXZ.x, ro.y, roXZ.y);
  rd = vec3(rdXZ.x, rd.y, rdXZ.y);
  vec2 roYZ = rot2(ro.yz, uRot.y);
  vec2 rdYZ = rot2(rd.yz, uRot.y);
  ro = vec3(ro.x, roYZ.x, roYZ.y) + uTarget;
  rd = vec3(rd.x, rdYZ.x, rdYZ.y);

  vec2 hit = march(ro, rd);
  if (hit.x >= 0.0) return vec4(shade(ro, rd, hit.x, hit.y), 1.0);
#if TRANSPARENT
  return vec4(0.0);
#else
  vec3 bg = mix(vec3(0.055), vec3(0.118), clamp(uvn.y * 0.5 + 0.5, 0.0, 1.0));
  return vec4(bg * clamp(1.0 - 0.175 * dot(uv, uv), 0.0, 1.0), 1.0);
#endif
}`;
}

/** WebGL2 fragment shader (pair with GL_VERTEX in the runtime). */
export function renderGlsl(sceneGlsl: string, fnName: string, c: RenderConstants): string {
  return `#version 300 es
precision highp float;
precision highp int;

uniform vec2 uRes;   // canvas size in pixels
uniform vec2 uRot;   // orbit yaw, pitch (radians)
uniform float uDist; // orbit distance
uniform float uTime; // seconds
uniform vec3 uTarget; // orbit center
out vec4 outColor;

// ── Scene SDF (generated by d-stance) ──────────────────────────────────────

${sceneGlsl}

// ── Renderer ────────────────────────────────────────────────────────────────

${glslRenderer(fnName, c)}

void main() {
  outColor = render(vec2(gl_FragCoord.x, uRes.y - gl_FragCoord.y));
}
`;
}

/**
 * Shadertoy "Image" tab: paste as-is. Drag to orbit (iMouse); the view
 * starts where the editor camera was.
 */
export function renderShadertoy(
  sceneGlsl: string,
  fnName: string,
  c: RenderConstants,
  view: { rotX: number; rotY: number; distance: number; target: readonly [number, number, number] },
): string {
  return `// Made with d-stance — drag to orbit.

${sceneGlsl}

// ── Renderer ────────────────────────────────────────────────────────────────

vec2 uRes;
vec2 uRot;
float uDist;
vec3 uTarget;

${glslRenderer(fnName, c)}

void mainImage(out vec4 fragColor, in vec2 fragCoord) {
  uRes = iResolution.xy;
  uRot = vec2(${num(view.rotX)}, ${num(view.rotY)});
  if (iMouse.x > 0.0) uRot += (iMouse.xy / iResolution.xy - 0.5) * vec2(6.2831853, -3.1415926);
  uDist = ${num(view.distance)};
  uTarget = vec3(${view.target.map(num).join(", ")});
  vec4 c = render(vec2(fragCoord.x, iResolution.y - fragCoord.y));
  fragColor = vec4(c.rgb, 1.0);
}
`;
}
